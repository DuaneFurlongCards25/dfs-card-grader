/**
 * Inlines src/scanner.html into src/scanner.gen.ts so the Worker can serve the
 * phone app itself — no second deploy, no Pages project, and the page is always
 * the same version as the endpoints it calls.
 *
 * Run by `npm run deploy`. Never edit scanner.gen.ts by hand.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const html = readFileSync(join(here, 'src/scanner.html'), 'utf8');

// Escape only what breaks a template literal.
const safe = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

writeFileSync(
  join(here, 'src/scanner.gen.ts'),
  `// GENERATED by build-scanner.mjs from scanner.html — do not edit.\n` +
  `export const SCANNER_HTML = \`${safe}\`;\n`
);

console.log(`scanner.gen.ts written (${(html.length / 1024).toFixed(1)} KB)`);
